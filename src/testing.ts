/**
 * Options for lambda()
 */
export interface LambdaAdapterOptions {
  /** 'v1' for API Gateway REST API events, 'v2' for HTTP API and function URL events (default: 'v1') */
  event?: 'v1' | 'v2';
  /** properties of the Lambda context object passed to the handler */
  context?: { [key: string]: unknown };
}

type LambdaHandler = (event: any, context: any, callback?: (error?: unknown, result?: any) => void) => any;

/**
 * Creates an adapter that sends requests to an AWS Lambda handler as API Gateway events
 *
 * @param handler - the Lambda handler
 * @param options - the event format and Lambda context
 */
export function lambda(handler: LambdaHandler, options: LambdaAdapterOptions = {}): TestAdapter {
  const version = options.event || 'v1';
  return {
    async send(request) {
      const requestId = randomUUID();
      const event = version === 'v2' ? lambdaEventV2(request, requestId) : lambdaEventV1(request, requestId);
      const context = {
        callbackWaitsForEmptyEventLoop: true,
        functionName: 'openapi-backend-test',
        functionVersion: '$LATEST',
        invokedFunctionArn: 'arn:aws:lambda:us-east-1:000000000000:function:openapi-backend-test',
        memoryLimitInMB: '128',
        awsRequestId: requestId,
        logGroupName: '/aws/lambda/openapi-backend-test',
        logStreamName: 'openapi-backend-test',
        getRemainingTimeInMillis: () => 30000,
        ...options.context,
      };
      const result = await new Promise<any>((resolve, reject) => {
        const callback = (error?: unknown, value?: unknown) => (error ? reject(error) : resolve(value));
        try {
          const returned = handler(event, context, callback);
          if (returned && typeof returned.then === 'function') {
            returned.then(resolve, reject);
          } else if (handler.length < 3) {
            resolve(returned);
          }
        } catch (error) {
          reject(error);
        }
      });
      return lambdaResponse(result, version);
    },
  };
}

function encodeLambdaBody(request: SentRequest) {
  if (request.body === undefined) {
    return { body: null, isBase64Encoded: false };
  }
  const type = baseMediaType(request.headers['content-type']);
  if (Buffer.isBuffer(request.body) && !(type && isTextMediaType(type))) {
    return { body: request.body.toString('base64'), isBase64Encoded: true };
  }
  return { body: request.body.toString(), isBase64Encoded: false };
}

function lambdaEventV1(request: SentRequest, requestId: string) {
  const query = new URLSearchParams(request.query);
  const multiValueQuery: { [name: string]: string[] } = {};
  query.forEach((value, name) => {
    multiValueQuery[name] = [...(multiValueQuery[name] || []), value];
  });
  const hasQuery = Object.keys(multiValueQuery).length > 0;
  return {
    resource: '/{proxy+}',
    path: request.path,
    httpMethod: request.method,
    headers: { ...request.headers },
    multiValueHeaders: _.mapValues(request.headers, (value) => [value]),
    queryStringParameters: hasQuery ? _.mapValues(multiValueQuery, (values) => values[values.length - 1]) : null,
    multiValueQueryStringParameters: hasQuery ? multiValueQuery : null,
    pathParameters: { proxy: request.path.replace(/^\//, '') },
    stageVariables: null,
    requestContext: {
      accountId: '000000000000',
      apiId: 'openapi-backend-test',
      httpMethod: request.method,
      path: request.path,
      protocol: 'HTTP/1.1',
      requestId,
      requestTimeEpoch: Date.now(),
      resourcePath: '/{proxy+}',
      stage: 'test',
      identity: { sourceIp: '127.0.0.1', userAgent: request.headers['user-agent'] || null },
    },
    ...encodeLambdaBody(request),
  };
}

function lambdaEventV2(request: SentRequest, requestId: string) {
  const query = new URLSearchParams(request.query);
  const queryStringParameters: { [name: string]: string } = {};
  query.forEach((value, name) => {
    queryStringParameters[name] = name in queryStringParameters ? `${queryStringParameters[name]},${value}` : value;
  });
  const { cookie, ...headers } = request.headers;
  return {
    version: '2.0',
    routeKey: '$default',
    rawPath: request.path,
    rawQueryString: request.query,
    ...(cookie ? { cookies: cookie.split(/;\s*/) } : {}),
    headers,
    ...(Object.keys(queryStringParameters).length ? { queryStringParameters } : {}),
    requestContext: {
      accountId: '000000000000',
      apiId: 'openapi-backend-test',
      domainName: 'localhost',
      http: {
        method: request.method,
        path: request.path,
        protocol: 'HTTP/1.1',
        sourceIp: '127.0.0.1',
        userAgent: request.headers['user-agent'] || '',
      },
      requestId,
      routeKey: '$default',
      stage: '$default',
      time: new Date().toISOString(),
      timeEpoch: Date.now(),
    },
    ...encodeLambdaBody(request),
  };
}

function lambdaResponse(result: any, version: 'v1' | 'v2'): TestAdapterResponse {
  if (version === 'v2' && !(result && typeof result === 'object' && typeof result.statusCode === 'number')) {
    // API Gateway infers the response for payload format 2.0
    return {
      status: 200,
      headers: { 'content-type': 'application/json' },
      body: typeof result === 'string' ? result : JSON.stringify(result),
    };
  }
  if (!result || typeof result.statusCode !== 'number') {
    throw new TypeError(
      `The Lambda handler returned ${JSON.stringify(result)?.slice(0, 200)}, which isn't an API Gateway proxy result ` +
        'like { statusCode, headers, body }',
    );
  }
  const headers: { [name: string]: string } = {};
  for (const [name, values] of Object.entries((result.multiValueHeaders || {}) as { [name: string]: unknown[] })) {
    headers[name.toLowerCase()] = values.map(String).join(', ');
  }
  for (const [name, value] of Object.entries((result.headers || {}) as { [name: string]: unknown })) {
    headers[name.toLowerCase()] = String(value);
  }
  if (Array.isArray(result.cookies) && result.cookies.length) {
    headers['set-cookie'] = result.cookies.join(', ');
  }
  if (!headers['content-type']) {
    // API Gateway's default content type
    headers['content-type'] = 'application/json';
  }
  const body =
    result.body === undefined || result.body === null
      ? undefined
      : result.isBase64Encoded
        ? Buffer.from(String(result.body), 'base64')
        : String(result.body);
  return { status: result.statusCode, headers, body };
}

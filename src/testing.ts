/**
 * Creates a test client for an OpenAPIBackend instance
 *
 * @param api - the OpenAPIBackend instance
 * @param options - the app that serves your API, and options for every request
 * @returns a test client with a method for every operation
 */
export function createTestClient<Ops = UnknownOperations>(
  api: OpenAPIBackend<any>,
  options: TestClientOptions = {},
): TestClient<Ops> {
  const { app, basePath, transformResponse, ...defaults } = options;
  return buildClient<Ops>({
    api,
    transport: createTransport(api, app, transformResponse),
    basePath,
    defaults: mergeDefaults({}, defaults),
  });
}

interface ClientState {
  api: OpenAPIBackend<any>;
  transport: Transport;
  basePath?: string;
  defaults: RequestDefaults;
}

// properties test runners and other libraries look up on objects, which must not become operation methods
const reservedProperties = new Set(['then', 'catch', 'finally', 'toJSON', 'asymmetricMatch', 'nodeType', 'tagName']);

function buildClient<Ops>(state: ClientState): TestClient<Ops> {
  const methods: TestClientMethods<Ops> = {
    api: state.api,
    call: (operationId: string, request?: OperationRequest) => callOperation(state, operationId, request),
    request: (request: string | RawRequest, options?: RawRequestOptions) => sendRawRequest(state, request, options),
    with: (defaults: RequestDefaults) =>
      buildClient<Ops>({ ...state, defaults: mergeDefaults(state.defaults, defaults) }),
  };
  const operationMethods = new Map<string, OperationMethod>();
  return new Proxy(methods, {
    get(target, property, receiver) {
      if (typeof property === 'symbol' || property in target) {
        return Reflect.get(target, property, receiver);
      }
      if (reservedProperties.has(property) || /^(@@|__|\$\$)/.test(property)) {
        return undefined;
      }
      if (!operationMethods.has(property)) {
        operationMethods.set(property, (request?: OperationRequest) => callOperation(state, property, request));
      }
      return operationMethods.get(property);
    },
  }) as TestClient<Ops>;
}

/*
 * Sending requests
 */

interface OutgoingRequest extends SentRequest {
  /** the body the way a body parser would pass it to api.handleRequest() */
  parsedBody?: unknown;
}

async function callOperation(state: ClientState, operationId: string, request: OperationRequest = {}) {
  const { api } = state;
  await initialize(api);

  const operation = api.getOperation(operationId);
  if (!operation) {
    throw new Error(unknownOperationMessage(api, operationId));
  }

  const options = mergeRequest(state.defaults, request as TestRequest);
  const parts = options.example
    ? await exampleRequest(state, operation, options.example, options)
    : _.pick(options, ['params', 'query', 'headers', 'cookies', 'body']);

  const outgoing = await buildRequest(state, {
    method: operation.method,
    path: fillPathTemplate(operation, parts.params || {}),
    query: serializeQuery(parts.query, operation.parameters as ParameterObject[]),
    headers: parts.headers,
    cookies: parts.cookies,
    body: parts.body,
    contentType: options.contentType,
    operation,
  });

  // make sure the request reaches the operation it was built for
  const matched = api.matchOperation(routerRequest(state, outgoing));
  if (matched?.operationId !== operationId) {
    throw routingError(operation, matched, parts.params, outgoing);
  }

  return send(state, outgoing, options);
}

async function sendRawRequest(state: ClientState, request: string | RawRequest, options: RawRequestOptions = {}) {
  const { api } = state;
  await initialize(api);

  const { method, path, ...requestOptions } = typeof request === 'string' ? parseRawRequest(request) : request;
  const defaults = _.omit(state.defaults, ['example']);
  const merged = mergeRequest(defaults, { ...requestOptions, ...options });

  const [pathname, queryString = ''] = path.split('?');
  const operation = api.matchOperation(
    routerRequest(state, { method: method.toUpperCase(), path: pathname, query: queryString, headers: {} }),
  );
  const query = [queryString, serializeQuery(merged.query, (operation?.parameters as ParameterObject[]) || [])]
    .filter(Boolean)
    .join('&');

  const outgoing = await buildRequest(state, {
    method,
    path: pathname,
    query,
    headers: merged.headers,
    cookies: merged.cookies,
    body: merged.body,
    contentType: merged.contentType,
    operation,
    raw: true,
  });

  return send(state, outgoing, merged);
}

function parseRawRequest(request: string): { method: string; path: string } {
  const match = request.trim().match(/^([A-Za-z]+)\s+(\S+)$/);
  if (!match) {
    throw new TypeError(`Can't parse request "${request}". Use the method and path, like "GET /pets?limit=10"`);
  }
  return { method: match[1], path: match[2] };
}

const testHeader = 'x-openapi-backend-test-id';

async function send(state: ClientState, outgoing: OutgoingRequest, options: TestRequest): Promise<TestResponse> {
  const { api, transport } = state;
  const sentRequest = _.omit(outgoing, ['parsedBody']) as SentRequest;

  if (options.security && !transport.inProcess) {
    throw new Error(
      'Security stubs only work when the request is handled in the same process as your tests, not with a running server',
    );
  }

  // link the request to the context openapi-backend builds for it
  const pending = transport.inProcess ? testHooks(api).pending : undefined;
  const id = randomUUID();
  const linked: PendingRequest = { security: options.security };
  if (pending) {
    pending.set(id, linked);
    outgoing = { ...outgoing, headers: { ...outgoing.headers, [testHeader]: id } };
  }

  let received: ReceivedResponse;
  try {
    received = await transport.send(outgoing);
  } finally {
    pending?.delete(id);
  }

  const context = linked.context as Context | undefined;
  const operation = context
    ? (context.operation as Operation | undefined)
    : api.matchOperation(routerRequest(state, outgoing));

  const response: TestResponse = {
    status: received.status,
    headers: received.headers,
    body: received.body,
    operationId: operation?.operationId,
  } as TestResponse;
  Object.defineProperties(response, {
    operation: { value: operation, enumerable: false },
    context: { value: context, enumerable: false },
    request: { value: sentRequest, enumerable: false },
  });

  if (operation && options.validateResponse !== false) {
    validateResponse(api, operation, response, received);
  }

  return response;
}


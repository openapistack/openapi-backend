interface PendingRequest {
  context?: Partial<Context>;
  security?: { [scheme: string]: unknown };
}

interface TestHooks {
  pending: Map<string, PendingRequest>;
  onRequest(req: BackendRequest, context: Partial<Context>): { security?: { [scheme: string]: unknown } } | undefined;
}

// the same global symbol is read by OpenAPIBackend.handleRequest()
const testHooksKey = Symbol.for('openapi-backend.testHooks');

function testHooks(api: OpenAPIBackend<any>): TestHooks {
  const existing = (api as any)[testHooksKey] as TestHooks | undefined;
  if (existing) {
    return existing;
  }
  const pending = new Map<string, PendingRequest>();
  const hooks: TestHooks = {
    pending,
    onRequest(req, context) {
      const header = Object.keys(req.headers || {}).find((name) => name.toLowerCase() === testHeader);
      const value = header ? req.headers[header] : undefined;
      const linked = pending.get(Array.isArray(value) ? value[0] : value);
      if (!linked) {
        return undefined;
      }
      linked.context = context;
      return { security: linked.security };
    },
  };
  Object.defineProperty(api, testHooksKey, { value: hooks, configurable: true });
  return hooks;
}

const initializing = new WeakMap<object, Promise<unknown>>();

async function initialize(api: OpenAPIBackend<any>) {
  if (api.initialized) {
    return;
  }
  if (!initializing.has(api)) {
    initializing.set(api, api.init());
  }
  await initializing.get(api);
}

/*
 * Messages
 */

function unknownOperationMessage(api: OpenAPIBackend<any>, operationId: string) {
  const operationIds = api
    .getOperations()
    .map((operation) => operation.operationId)
    .filter(Boolean) as string[];
  const closest = _.minBy(operationIds, (candidate) => distance(candidate.toLowerCase(), operationId.toLowerCase()));
  const suggestion =
    closest && distance(closest.toLowerCase(), operationId.toLowerCase()) <= Math.max(2, operationId.length / 3)
      ? ` Did you mean "${closest}"?`
      : '';
  return `Unknown operationId "${operationId}".${suggestion}`;
}

/**
 * Levenshtein distance
 */
function distance(a: string, b: string) {
  let previous = Array.from({ length: b.length + 1 }, (_value, i) => i);
  for (let i = 1; i <= a.length; i++) {
    const current = [i];
    for (let j = 1; j <= b.length; j++) {
      current[j] = Math.min(previous[j] + 1, current[j - 1] + 1, previous[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
    }
    previous = current;
  }
  return previous[b.length];
}

function routingError(
  operation: Operation,
  matched: Operation | undefined,
  params: { [name: string]: unknown } | undefined,
  request: OutgoingRequest,
) {
  const sent = `${request.method} ${request.url}`;
  const target = matched
    ? `the router matched ${matched.operationId} (${matched.method.toUpperCase()} ${matched.path}) instead`
    : 'no operation matches it';
  const values = _.isEmpty(params)
    ? ''
    : ` with ${JSON.stringify(params)
        .replace(/"([^"]+)":/g, ' $1: ')
        .replace(/}$/, ' }')}`;
  return new RoutingError(
    `client.${operation.operationId}() sent ${sent}, but ${target}.\n` +
      `${operation.operationId} can't be reached${values}.`,
    {
      operationId: operation.operationId as string,
      matchedOperationId: matched?.operationId,
      request: toSentRequest(request),
    },
  );
}

function formatExchange(response: TestResponse) {
  const { request } = response;
  const route = response.operationId ? `  →  ${response.operationId}` : '';
  const lines = [
    `${request.method} ${request.url}${route}`,
    `${response.status} ${http.STATUS_CODES[response.status] || ''}`.trim(),
  ];
  if (response.body !== undefined) {
    const text = Buffer.isBuffer(response.body)
      ? `<${response.body.length} bytes>`
      : typeof response.body === 'string'
        ? response.body
        : JSON.stringify(response.body, null, 2);
    const bodyLines = text.split('\n');
    lines.push(...bodyLines.slice(0, 20), ...(bodyLines.length > 20 ? ['…'] : []));
  }
  return lines.map((line) => `  ${line}`).join('\n');
}

function formatIssues(issues: ResponseValidationIssue[]) {
  const width = Math.max(...issues.map((issue) => issue.location.length));
  return issues.map((issue) => `  ${issue.location.padEnd(width)}  ${issue.message}`).join('\n');
}

/**
 * Turns a JSON pointer into a readable location, like body.tags[0].name
 */
function readableLocation(prefix: string, pointer: string, property?: string) {
  const segments = pointer
    .split('/')
    .slice(1)
    .map((segment) => segment.replace(/~1/g, '/').replace(/~0/g, '~'));
  if (property !== undefined) {
    segments.push(property);
  }
  return segments.reduce((location, segment) => {
    if (/^\d+$/.test(segment)) return `${location}[${segment}]`;
    if (/^[A-Za-z_$][\w$-]*$/.test(segment)) return location ? `${location}.${segment}` : segment;
    return `${location}[${JSON.stringify(segment)}]`;
  }, prefix);
}

function errorMessage(error: ErrorObject) {
  if (error.keyword === 'enum' && Array.isArray((error.params as any)?.allowedValues)) {
    return `${error.message}: ${(error.params as any).allowedValues.join(', ')}`;
  }
  return error.message || error.keyword;
}

function schemaIssue(prefix: string, error: ErrorObject): ResponseValidationIssue {
  const params = (error.params || {}) as any;
  const property = error.keyword === 'required' ? params.missingProperty : undefined;
  const extra = error.keyword === 'additionalProperties' ? params.additionalProperty : undefined;
  return {
    location: readableLocation(prefix, error.instancePath || '', property ?? extra),
    message: errorMessage(error),
  };
}

/**
 * Request validation errors point into { path, query, header, cookie, requestBody }
 */
function requestValidationIssue(error: ErrorObject): ResponseValidationIssue {
  const issue = schemaIssue('', error);
  const location = issue.location
    .replace(/^requestBody/, 'body')
    .replace(/^path\b/, 'params')
    .replace(/^header\b/, 'headers')
    .replace(/^cookie\b/, 'cookies');
  return { ...issue, location: location || 'body' };
}


/**
 * Options that can be set for every request, with createTestClient() or client.with()
 */
export interface RequestDefaults {
  /** request headers */
  headers?: { [name: string]: string | number | boolean | string[] | undefined };
  /** query parameters, serialized with the style and explode of each parameter in the spec */
  query?: { [name: string]: unknown };
  /** cookies, sent in the Cookie header */
  cookies?: { [name: string]: string | number | boolean | undefined };
  /** the media type to send the body as */
  contentType?: string;
  /** build requests from the examples in the spec. A string picks a named example */
  example?: boolean | string;
  /** results to use instead of calling the security handlers, by security scheme name */
  security?: { [scheme: string]: unknown };
  /** check responses against the spec (default: true) */
  validateResponse?: boolean;
}

/**
 * Options for a single request
 */
export interface TestRequest extends RequestDefaults {
  /** path parameters, filled into the path template */
  params?: { [name: string]: unknown };
  /** the request body */
  body?: unknown;
}

type ParamsOf<Op> = Op extends { params: infer P } ? P : { [name: string]: unknown };
type QueryOf<Op> = Op extends { query: infer Q } ? Q : { [name: string]: unknown };
type BodyOf<Op> = Op extends { requestBody: infer B } ? B : unknown;
type ResponseOf<Op> = Op extends { response: infer R } ? R : any;

/**
 * Makes every property optional, recursively. Setting a property to undefined removes it from the example.
 */
export type DeepPartial<T> = T extends Buffer | Date | ((...args: any[]) => any) | any[]
  ? T
  : T extends object
    ? { [K in keyof T]?: DeepPartial<T[K]> | undefined }
    : T;

type BaseOperationRequest = Omit<TestRequest, 'params' | 'query' | 'body' | 'example'>;

/**
 * Request options for an operation method. Typed from the Operations type generated by `openapi typegen --backend`
 */
export type OperationRequest<Op = any> =
  | (BaseOperationRequest & {
      example?: false;
      params?: ParamsOf<Op>;
      query?: QueryOf<Op>;
      body?: BodyOf<Op>;
    })
  | (BaseOperationRequest & {
      example: true | string;
      params?: DeepPartial<ParamsOf<Op>>;
      query?: DeepPartial<QueryOf<Op>>;
      body?: DeepPartial<BodyOf<Op>>;
    });


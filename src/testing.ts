/**
 * Thrown when the request built for an operation is routed to another operation, or to none
 */
export class RoutingError extends Error {
  public operationId: string;
  public matchedOperationId: string | undefined;
  public request: SentRequest;

  constructor(message: string, props: { operationId: string; matchedOperationId?: string; request: SentRequest }) {
    super(message);
    this.name = 'RoutingError';
    this.operationId = props.operationId;
    this.matchedOperationId = props.matchedOperationId;
    this.request = props.request;
  }
}

/**
 * Thrown when a response doesn't match the API definition
 */
export class ResponseValidationError extends Error {
  public response: TestResponse;
  public errors: ResponseValidationIssue[];

  constructor(message: string, props: { response: TestResponse; errors: ResponseValidationIssue[] }) {
    super(message);
    this.name = 'ResponseValidationError';
    this.response = props.response;
    this.errors = props.errors;
  }
}


interface RequestParts {
  method: string;
  path: string;
  query: string;
  headers?: TestRequest['headers'];
  cookies?: TestRequest['cookies'];
  body?: unknown;
  contentType?: string;
  operation?: Operation;
  raw?: boolean;
}

async function buildRequest(state: ClientState, parts: RequestParts): Promise<OutgoingRequest> {
  const method = parts.method.toUpperCase();
  const path = parts.raw ? parts.path : joinPaths(basePathOf(state), parts.path);
  const headers = normalizeHeaders(parts.headers, parts.operation);

  const cookies = serializeCookies(parts.cookies);
  if (cookies) {
    headers['cookie'] = headers['cookie'] ? `${headers['cookie']}; ${cookies}` : cookies;
  }

  const contentType =
    parts.contentType || baseMediaType(headers['content-type']) || preferredMediaType(parts.operation);
  const body = await encodeBody(parts.body, contentType);
  if (body.contentType && (!headers['content-type'] || body.contentType.startsWith('multipart/'))) {
    // multipart bodies need the boundary the encoder picked
    headers['content-type'] = body.contentType;
  }
  if (body.encoded !== undefined) {
    headers['content-length'] = String(Buffer.byteLength(body.encoded));
  }

  return {
    method,
    path,
    url: parts.query ? `${path}?${parts.query}` : path,
    query: parts.query,
    headers,
    body: body.encoded,
    parsedBody: body.parsed,
  };
}

function basePathOf(state: ClientState) {
  return state.basePath ?? state.api.apiRoot ?? '/';
}

function joinPaths(base: string, path: string) {
  const prefix = base.replace(/\/+$/, '');
  return `${prefix}${path.startsWith('/') ? '' : '/'}${path}`;
}

/**
 * The request as the router sees it: basePath replaced with the apiRoot
 */
function routerRequest(
  state: ClientState,
  request: Pick<SentRequest, 'method' | 'path' | 'query' | 'headers'>,
): BackendRequest {
  const basePath = basePathOf(state).replace(/\/+$/, '');
  const apiRoot = (state.api.apiRoot || '/').replace(/\/+$/, '');
  let path = request.path;
  if (basePath !== apiRoot && (path === basePath || path.startsWith(`${basePath}/`))) {
    path = joinPaths(apiRoot || '/', path.slice(basePath.length) || '/');
  }
  return {
    method: request.method,
    path: request.query ? `${path}?${request.query}` : path,
    headers: request.headers,
  };
}

function fillPathTemplate(operation: Operation, params: { [name: string]: unknown }) {
  const parameters = (operation.parameters || []) as ParameterObject[];
  const names = (operation.path.match(/\{[^}]+\}/g) || []).map((token) => token.slice(1, -1));
  for (const name of Object.keys(params)) {
    if (!names.includes(name) && params[name] !== undefined) {
      throw new Error(
        `Unknown path parameter "${name}" for ${operation.operationId} (${operation.method.toUpperCase()} ${operation.path}). ` +
          (names.length ? `Its path parameters are: ${names.join(', ')}` : 'It has no path parameters'),
      );
    }
  }
  return operation.path.replace(/\{([^}]+)\}/g, (_token, name: string) => {
    const value = params[name];
    if (value === undefined || value === null) {
      throw new Error(
        `Missing path parameter "${name}" for ${operation.operationId} (${operation.method.toUpperCase()} ${operation.path})`,
      );
    }
    const parameter = parameters.find((param) => param.in === 'path' && param.name === name);
    return serializePathParameter(name, value, parameter);
  });
}

const encode = (value: unknown) =>
  encodeURIComponent(_.isPlainObject(value) || Array.isArray(value) ? JSON.stringify(value) : String(value));

function serializePathParameter(name: string, value: unknown, parameter?: ParameterObject) {
  const style = parameter?.style || 'simple';
  const explode = parameter?.explode ?? false;
  if (Array.isArray(value)) {
    const items = value.map(encode);
    if (style === 'label') return `.${items.join(explode ? '.' : ',')}`;
    if (style === 'matrix') return explode ? items.map((item) => `;${name}=${item}`).join('') : `;${name}=${items}`;
    return items.join(',');
  }
  if (_.isPlainObject(value)) {
    const entries = Object.entries(value as object);
    const pairs = entries.map(([key, val]) => `${encode(key)}=${encode(val)}`);
    const flat = _.flatten(entries).map(encode);
    if (style === 'label') return `.${explode ? pairs.join('.') : flat.join(',')}`;
    if (style === 'matrix') return explode ? pairs.map((pair) => `;${pair}`).join('') : `;${name}=${flat.join(',')}`;
    return explode ? pairs.join(',') : flat.join(',');
  }
  if (style === 'label') return `.${encode(value)}`;
  if (style === 'matrix') return `;${name}=${encode(value)}`;
  return encode(value);
}

function serializeQuery(query: { [name: string]: unknown } | undefined, parameters: ParameterObject[] = []) {
  const pairs: string[] = [];
  for (const [name, value] of Object.entries(query || {})) {
    if (value === undefined) {
      continue;
    }
    const key = encodeURIComponent(name);
    const parameter = parameters.find((param) => param.in === 'query' && param.name === name);
    if (parameter?.content) {
      pairs.push(`${key}=${encodeURIComponent(typeof value === 'string' ? value : JSON.stringify(value))}`);
      continue;
    }
    const style = parameter?.style || 'form';
    const explode = parameter?.explode ?? style === 'form';
    if (value === null) {
      pairs.push(`${key}=`);
    } else if (Array.isArray(value)) {
      if (explode && style === 'form') {
        pairs.push(...value.map((item) => `${key}=${encode(item)}`));
      } else {
        const delimiter = style === 'spaceDelimited' ? '%20' : style === 'pipeDelimited' ? '|' : ',';
        pairs.push(`${key}=${value.map(encode).join(delimiter)}`);
      }
    } else if (_.isPlainObject(value)) {
      const entries = Object.entries(value as object);
      if (style === 'deepObject') {
        pairs.push(...entries.map(([prop, val]) => `${key}[${encodeURIComponent(prop)}]=${encode(val)}`));
      } else if (explode) {
        pairs.push(...entries.map(([prop, val]) => `${encodeURIComponent(prop)}=${encode(val)}`));
      } else {
        pairs.push(`${key}=${_.flatten(entries).map(encode).join(',')}`);
      }
    } else {
      pairs.push(`${key}=${encode(value)}`);
    }
  }
  return pairs.join('&');
}

/**
 * Header parameters use the simple style: arrays and objects are sent as comma separated values
 */
function serializeSimple(value: unknown, explode = false): string {
  if (Array.isArray(value)) {
    return value.map((item) => serializeSimple(item)).join(',');
  }
  if (_.isPlainObject(value)) {
    const entries = Object.entries(value as object);
    return explode
      ? entries.map(([key, val]) => `${key}=${serializeSimple(val)}`).join(',')
      : _.flatten(entries)
          .map((item) => serializeSimple(item))
          .join(',');
  }
  return String(value);
}

function normalizeHeaders(headers: TestRequest['headers'] = {}, operation?: Operation) {
  const parameters = ((operation?.parameters || []) as ParameterObject[]).filter((param) => param.in === 'header');
  const normalized: { [name: string]: string } = {};
  for (const [name, value] of Object.entries(headers)) {
    if (value === undefined) {
      continue;
    }
    const parameter = parameters.find((param) => param.name.toLowerCase() === name.toLowerCase());
    normalized[name.toLowerCase()] = serializeSimple(value, parameter?.explode);
  }
  return normalized;
}

function serializeCookies(cookies: TestRequest['cookies'] = {}) {
  return Object.entries(cookies)
    .filter(([, value]) => value !== undefined)
    .map(([name, value]) => `${name}=${encodeURIComponent(serializeSimple(value))}`)
    .join('; ');
}

function baseMediaType(contentType?: string) {
  return contentType ? contentType.split(';')[0].trim().toLowerCase() : undefined;
}

function isJsonMediaType(mediaType?: string) {
  return Boolean(mediaType && /^application\/(.+\+)?json$/.test(baseMediaType(mediaType)));
}

function preferredMediaType(operation?: Operation): string | undefined {
  const requestBody = operation?.requestBody as RequestBodyObject | undefined;
  const mediaTypes = Object.keys(requestBody?.content || {});
  return mediaTypes.find((type) => type === 'application/json') || mediaTypes.find(isJsonMediaType) || mediaTypes[0];
}

interface EncodedBody {
  encoded?: string | Buffer;
  parsed?: unknown;
  contentType?: string;
}

async function encodeBody(body: unknown, mediaType?: string): Promise<EncodedBody> {
  if (body === undefined) {
    return {};
  }
  if (typeof body === 'string' || Buffer.isBuffer(body)) {
    return { encoded: body, parsed: body, contentType: mediaType };
  }
  if (body instanceof Uint8Array) {
    return { encoded: Buffer.from(body), parsed: Buffer.from(body), contentType: mediaType };
  }
  if (body instanceof URLSearchParams) {
    return {
      encoded: body.toString(),
      parsed: formFields(body),
      contentType: mediaType || 'application/x-www-form-urlencoded',
    };
  }
  if (body instanceof FormData) {
    return encodeFormData(body);
  }

  const type = baseMediaType(mediaType) || 'application/json';
  if (type === 'application/x-www-form-urlencoded') {
    const params = new URLSearchParams();
    for (const [key, value] of Object.entries(body as object)) {
      for (const item of Array.isArray(value) ? value : [value]) {
        if (item !== undefined) params.append(key, _.isPlainObject(item) ? JSON.stringify(item) : String(item));
      }
    }
    return { encoded: params.toString(), parsed: formFields(params), contentType: mediaType };
  }
  if (type === 'multipart/form-data') {
    const form = new FormData();
    for (const [key, value] of Object.entries(body as object)) {
      for (const item of Array.isArray(value) ? value : [value]) {
        if (item === undefined) continue;
        if (Buffer.isBuffer(item) || item instanceof Uint8Array) form.append(key, new Blob([item]), key);
        else if (item instanceof Blob) form.append(key, item);
        else form.append(key, _.isPlainObject(item) ? JSON.stringify(item) : String(item));
      }
    }
    return encodeFormData(form);
  }
  if (type.startsWith('text/') && !_.isPlainObject(body) && !Array.isArray(body)) {
    return { encoded: String(body), parsed: String(body), contentType: mediaType };
  }
  return { encoded: JSON.stringify(body), parsed: body, contentType: mediaType || 'application/json' };
}

async function encodeFormData(form: FormData): Promise<EncodedBody> {
  // let the platform encode the multipart body and pick a boundary
  const encoded = new Response(form);
  return {
    encoded: Buffer.from(await encoded.arrayBuffer()),
    parsed: formFields(form),
    contentType: encoded.headers.get('content-type') || undefined,
  };
}

/**
 * Form fields the way body parsers pass them on: strings, with arrays for repeated fields. Files are left out.
 */
function formFields(form: FormData | URLSearchParams) {
  const fields: { [name: string]: string | string[] } = {};
  form.forEach((value: unknown, name: string) => {
    if (typeof value !== 'string') return;
    const existing = fields[name];
    fields[name] = existing === undefined ? value : ([] as string[]).concat(existing, value);
  });
  return fields;
}

/*
 * Request options
 */

function mergeRecords<T extends object>(base?: T, override?: T): T | undefined {
  if (!override) return base;
  const merged: any = { ...(base || {}) };
  for (const [key, value] of Object.entries(override)) {
    if (value === undefined) delete merged[key];
    else merged[key] = value;
  }
  return merged;
}

function lowercaseKeys<T extends object>(headers?: T): T | undefined {
  return headers ? (_.mapKeys(headers, (_value, key: string) => key.toLowerCase()) as T) : headers;
}

function mergeDefaults(base: RequestDefaults, defaults: RequestDefaults): RequestDefaults {
  return mergeRequest(base, defaults);
}

function mergeRequest<T extends TestRequest>(defaults: RequestDefaults, request: T): T {
  const merged: any = { ...defaults, ...request };
  merged.headers = mergeRecords(lowercaseKeys(defaults.headers), lowercaseKeys(request.headers));
  merged.query = mergeRecords(defaults.query, request.query);
  merged.cookies = mergeRecords(defaults.cookies, request.cookies);
  merged.security = mergeRecords(defaults.security, request.security);
  return _.omitBy(merged, (value) => value === undefined) as T;
}

/**
 * Deep merges override into base. Undefined removes a property, arrays and other values replace.
 */
function deepMerge(base: unknown, override: unknown): unknown {
  if (_.isPlainObject(base) && _.isPlainObject(override)) {
    const merged: any = { ...(base as object) };
    for (const [key, value] of Object.entries(override as object)) {
      if (value === undefined) delete merged[key];
      else merged[key] = deepMerge(merged[key], value);
    }
    return merged;
  }
  return override;
}

/*
 * Requests from examples
 */

interface ExampleParts {
  params?: { [name: string]: unknown };
  query?: { [name: string]: unknown };
  headers?: TestRequest['headers'];
  cookies?: TestRequest['cookies'];
  body?: unknown;
}

const noExample = Symbol('no example');

function pickExample(
  source: { example?: unknown; examples?: { [name: string]: unknown } } | undefined,
  name: string | undefined,
  found: Set<string>,
): unknown {
  const examples = (source?.examples || {}) as { [name: string]: ExampleObject };
  if (name && examples[name]) {
    found.add(name);
    return examples[name].value;
  }
  if (source?.example !== undefined) {
    return source.example;
  }
  const first = Object.values(examples)[0];
  return first ? first.value : noExample;
}

function exampleFromSchema(schema: any, required: boolean): unknown {
  if (!schema) return noExample;
  if (schema.example !== undefined) return schema.example;
  if (Array.isArray(schema.examples) && schema.examples.length) return schema.examples[0];
  // optional parameters are only included when the spec has an example for them
  return required ? mock(schema as SchemaLike) : noExample;
}

async function exampleRequest(
  state: ClientState,
  operation: Operation,
  example: true | string,
  overrides: TestRequest,
): Promise<ExampleParts> {
  const name = typeof example === 'string' ? example : undefined;
  const found = new Set<string>();
  const generated: ExampleParts = {};

  const targets = { path: 'params', query: 'query', header: 'headers', cookie: 'cookies' } as const;
  for (const parameter of (operation.parameters || []) as ParameterObject[]) {
    const target = targets[parameter.in as keyof typeof targets];
    if (!target) continue;
    const required = parameter.in === 'path' || Boolean(parameter.required);
    const media = parameter.content ? Object.values(parameter.content)[0] : undefined;
    let value = pickExample(media || (parameter as any), name, found);
    if (value === noExample) {
      value = exampleFromSchema(media ? media.schema : parameter.schema, required);
    }
    if (value !== noExample) {
      generated[target] = { ...((generated[target] as object) || {}), [parameter.name]: _.cloneDeep(value) };
    }
  }

  const requestBody = operation.requestBody as RequestBodyObject | undefined;
  if (requestBody?.content) {
    const mediaType = overrides.contentType || preferredMediaType(operation);
    const media = requestBody.content[mediaType] as MediaTypeObject | undefined;
    let value = pickExample(media as any, name, found);
    if (value === noExample) {
      value = exampleFromSchema(media?.schema, true);
    }
    if (value !== noExample) {
      generated.body = _.cloneDeep(value);
    }
  }

  if (name && !found.has(name)) {
    const names = _.uniq([
      ...((operation.parameters || []) as ParameterObject[]).flatMap((param) => Object.keys(param.examples || {})),
      ...Object.values(requestBody?.content || {}).flatMap((media) => Object.keys(media.examples || {})),
    ]);
    throw new Error(
      `${operation.operationId} has no example named "${name}". ` +
        (names.length ? `Its examples are: ${names.join(', ')}` : 'It has no named examples'),
    );
  }

  await checkExample(state, operation, generated);

  // apply the overrides
  for (const key of ['params', 'query', 'headers', 'cookies', 'body'] as const) {
    if (key in overrides) {
      const override = key === 'headers' ? lowercaseKeys(overrides.headers) : overrides[key];
      const base = key === 'headers' ? lowercaseKeys(generated.headers) : generated[key];
      generated[key] = override === undefined ? undefined : (deepMerge(base, override) as any);
    }
  }
  return generated;
}

/**
 * Makes sure the generated example passes the API's own request validation
 */
async function checkExample(state: ClientState, operation: Operation, parts: ExampleParts) {
  const outgoing = await buildRequest(state, {
    method: operation.method,
    path: fillPathTemplate(operation, parts.params || {}),
    query: serializeQuery(parts.query, operation.parameters as ParameterObject[]),
    headers: parts.headers,
    cookies: parts.cookies,
    body: parts.body,
    operation,
  });
  const result = getValidator(state.api).validateRequest(
    {
      method: outgoing.method,
      path: routerRequest(state, outgoing).path,
      headers: outgoing.headers,
      body: outgoing.parsedBody,
    },
    operation,
  );
  if (result.errors?.length) {
    const lines = formatIssues(result.errors.map(requestValidationIssue));
    throw new Error(
      `The example request for ${operation.operationId} doesn't pass validation:\n\n${lines}\n\n` +
        'Add an example for it to your API definition, or pass the values yourself.',
    );
  }
}

/*
 * Transports
 */

interface ReceivedResponse {
  status: number;
  headers: { [name: string]: string };
  body: unknown;
  /** set when the content-type says JSON, but the body isn't valid JSON */
  invalidJson?: boolean;
}

interface Transport {
  /** whether requests are handled in the same process, so the client can see what openapi-backend did */
  inProcess: boolean;
  send(request: OutgoingRequest): Promise<ReceivedResponse>;
}

function createTransport(
  api: OpenAPIBackend<any>,
  app: TestApp | undefined,
  transformResponse: TestClientOptions['transformResponse'],
): Transport {
  if (app === undefined) {
    if (typeof transformResponse !== 'function') {
      throw new TypeError(
        'createTestClient(): pass the app that serves your API as `app`, or a `transformResponse` function that turns ' +
          'what api.handleRequest() returns into a response. See https://openapistack.co/docs/openapi-backend/testing/frameworks',
      );
    }
    return {
      inProcess: true,
      send: async (request) => {
        const result = await api.handleRequest({
          method: request.method,
          path: request.url,
          headers: request.headers,
          body: request.parsedBody,
        });
        return readResponse(await transformResponse(result));
      },
    };
  }

  if (typeof app === 'string' || app instanceof URL) {
    const baseUrl = String(app).replace(/\/+$/, '');
    return {
      inProcess: false,
      send: async (request) => readFetchResponse(await fetch(`${baseUrl}${request.url}`, fetchInit(request))),
    };
  }

  const candidate = app as any;
  if (typeof candidate.send === 'function') {
    return { inProcess: true, send: async (request) => readResponse(await candidate.send(toSentRequest(request))) };
  }
  if (typeof candidate.inject === 'function') {
    // Fastify, Hapi
    return {
      inProcess: true,
      send: async (request) => {
        const res = await candidate.inject({
          method: request.method,
          url: request.url,
          headers: request.headers,
          payload: request.body,
        });
        return readResponse({
          status: res.statusCode,
          headers: res.headers,
          body: res.rawPayload ?? res.payload,
        });
      },
    };
  }
  if (typeof candidate.fetch === 'function') {
    // Hono, Elysia and other apps built on the fetch API
    return {
      inProcess: true,
      send: async (request) =>
        readFetchResponse(await candidate.fetch(new Request(`http://localhost${request.url}`, fetchInit(request)))),
    };
  }
  if (typeof candidate.callback === 'function') {
    // Koa
    return nodeTransport(candidate.callback());
  }
  if (app instanceof http.Server) {
    const [listener] = app.listeners('request') as NodeRequestListener[];
    if (!listener) {
      throw new TypeError('createTestClient(): the http.Server passed as `app` has no request listener');
    }
    return nodeTransport(listener);
  }
  if (typeof app === 'function') {
    // Express, Connect and other Node.js request listeners
    return nodeTransport(app as NodeRequestListener);
  }
  throw new TypeError(
    'createTestClient(): unsupported `app`. See https://openapistack.co/docs/openapi-backend/testing/frameworks',
  );
}

function toSentRequest(request: OutgoingRequest): SentRequest {
  return _.omit(request, ['parsedBody']) as SentRequest;
}

function fetchInit(request: OutgoingRequest): RequestInit {
  const hasBody = request.body !== undefined && request.method !== 'GET' && request.method !== 'HEAD';
  return {
    method: request.method,
    headers: _.omit(request.headers, ['content-length']),
    body: hasBody ? request.body : undefined,
  };
}

/**
 * Serves a Node.js request listener on a random local port, and sends requests to it
 */
function nodeTransport(listener: NodeRequestListener): Transport {
  let address: Promise<AddressInfo> | undefined;
  const listen = () => {
    if (!address) {
      address = new Promise<AddressInfo>((resolve, reject) => {
        const server = http.createServer(listener);
        server.once('error', reject);
        server.listen(0, '127.0.0.1', () => {
          // don't keep the test process alive
          server.unref();
          resolve(server.address() as AddressInfo);
        });
      });
    }
    return address;
  };

  return {
    inProcess: true,
    send: async (request) => {
      const { port } = await listen();
      return new Promise<ReceivedResponse>((resolve, reject) => {
        const req = http.request(
          {
            host: '127.0.0.1',
            port,
            method: request.method,
            path: request.url,
            headers: request.headers,
            agent: false,
          },
          (res) => {
            const chunks: Buffer[] = [];
            res.on('data', (chunk: Buffer) => chunks.push(chunk));
            res.on('error', reject);
            res.on('end', () =>
              resolve(
                readResponse({ status: res.statusCode || 0, headers: res.headers as any, body: Buffer.concat(chunks) }),
              ),
            );
          },
        );
        req.on('error', reject);
        if (request.body !== undefined) {
          req.write(request.body);
        }
        req.end();
      });
    },
  };
}

/*
 * Reading responses
 */

async function readFetchResponse(response: Response): Promise<ReceivedResponse> {
  const headers: { [name: string]: string } = {};
  response.headers.forEach((value, name) => {
    const key = name.toLowerCase();
    headers[key] = headers[key] ? `${headers[key]}, ${value}` : value;
  });
  return readResponse({ status: response.status, headers, body: Buffer.from(await response.arrayBuffer()) });
}

function readResponse(response: TestAdapterResponse | Response): any {
  if (typeof Response !== 'undefined' && response instanceof Response) {
    return readFetchResponse(response);
  }
  if (!response || typeof (response as TestAdapterResponse).status !== 'number') {
    throw new TypeError(
      `Expected a response like { status, headers, body }, got ${JSON.stringify(response)?.slice(0, 200)}`,
    );
  }
  const { status, headers: rawHeaders = {}, body } = response as TestAdapterResponse;
  const headers: { [name: string]: string } = {};
  for (const [name, value] of Object.entries(rawHeaders)) {
    if (value !== undefined) {
      headers[name.toLowerCase()] = Array.isArray(value) ? value.join(', ') : String(value);
    }
  }
  return { status, headers, ...parseBody(body, headers['content-type']) };
}

function parseBody(body: unknown, contentType?: string): { body: unknown; invalidJson?: boolean } {
  if (typeof body !== 'string' && !Buffer.isBuffer(body)) {
    return { body };
  }
  if (body.length === 0) {
    return { body: undefined };
  }
  const type = baseMediaType(contentType);
  if (isJsonMediaType(type)) {
    const text = body.toString();
    try {
      return { body: JSON.parse(text) };
    } catch {
      return { body: text, invalidJson: true };
    }
  }
  if (Buffer.isBuffer(body) && type && !isTextMediaType(type)) {
    return { body };
  }
  return { body: body.toString() };
}

function isTextMediaType(type: string) {
  return (
    type.startsWith('text/') ||
    /[/+](json|xml)$/.test(type) ||
    ['application/javascript', 'application/x-www-form-urlencoded', 'application/graphql'].includes(type)
  );
}

/*
 * Response validation
 */

function findResponse(responses: { [status: string]: unknown }, status: number) {
  const range = `${String(status)[0]}XX`;
  const key =
    Object.keys(responses).find((code) => code === String(status)) ||
    Object.keys(responses).find((code) => code.toUpperCase() === range) ||
    Object.keys(responses).find((code) => code === 'default');
  return key ? { key, response: responses[key] as ResponseObject } : undefined;
}

function mediaTypeMatches(documented: string, actual: string) {
  const [type, subtype] = baseMediaType(documented).split('/');
  const [actualType, actualSubtype] = actual.split('/');
  return (type === '*' || type === actualType) && (subtype === '*' || subtype === actualSubtype);
}

function validateResponse(
  api: OpenAPIBackend<any>,
  operation: Operation,
  response: TestResponse,
  received: ReceivedResponse,
) {
  const responses = (operation.responses || {}) as { [status: string]: unknown };
  const documented = findResponse(responses, response.status);
  if (!documented) {
    const codes = Object.keys(responses);
    const list = codes.length > 1 ? `${codes.slice(0, -1).join(', ')} and ${codes[codes.length - 1]}` : codes[0];
    const message =
      `${operation.operationId} responded with an undocumented ${response.status}\n\n` +
      `${formatExchange(response)}\n\n` +
      (codes.length ? `  The API spec documents ${list}.` : '  The API spec documents no responses for it.');
    throw new ResponseValidationError(message, {
      response,
      errors: [{ location: 'status', message: `${response.status} isn't documented` }],
    });
  }

  const issues: ResponseValidationIssue[] = [];
  const content = documented.response.content || {};
  const mediaTypes = Object.keys(content);
  const hasBody = response.body !== undefined && response.request.method !== 'HEAD';
  const contentType = baseMediaType(response.headers['content-type']);

  if (mediaTypes.length && response.status !== 204 && response.status !== 304 && response.request.method !== 'HEAD') {
    let mediaType: string | undefined;
    if (contentType && hasBody) {
      mediaType = mediaTypes.find((type) => mediaTypeMatches(type, contentType));
      if (!mediaType) {
        issues.push({
          location: 'headers.content-type',
          message: `${contentType} isn't documented. The API spec documents ${mediaTypes.join(', ')}`,
        });
      }
    } else {
      mediaType = mediaTypes.find(isJsonMediaType) || mediaTypes[0];
    }

    const schema = mediaType ? content[mediaType]?.schema : undefined;
    if (!hasBody) {
      issues.push({ location: 'body', message: `is empty, but the API spec documents ${mediaTypes.join(', ')}` });
    } else if (received.invalidJson) {
      issues.push({ location: 'body', message: "isn't valid JSON" });
    } else if (schema && mediaType && (isJsonMediaType(mediaType) || mediaType.includes('*'))) {
      const validate = compileResponseSchema(api, operation, documented.key, mediaType, schema);
      if (!validate(response.body)) {
        issues.push(...(validate.errors || []).map((error) => schemaIssue('body', error)));
      }
    }
  }

  const headerResult = getValidator(api).validateResponseHeaders(response.headers, operation, {
    statusCode: response.status,
    setMatchType: 'superset' as SetMatchType,
  });
  for (const error of headerResult.errors || []) {
    // validation runs against { headers }, so locations start with /headers
    issues.push(schemaIssue('', error));
  }

  if (issues.length) {
    const message =
      `${operation.operationId}'s ${response.status} response doesn't match the API spec\n\n` +
      `${formatExchange(response)}\n\n${formatIssues(issues)}\n\n` +
      `  Documented at paths.${operation.path}.${operation.method}.responses.${documented.key}`;
    throw new ResponseValidationError(message, { response, errors: issues });
  }
}

const responseValidators = new WeakMap<object, Map<string, ValidateFunction>>();

function compileResponseSchema(
  api: OpenAPIBackend<any>,
  operation: Operation,
  status: string,
  mediaType: string,
  schema: unknown,
) {
  let cache = responseValidators.get(api);
  if (!cache) {
    cache = new Map();
    responseValidators.set(api, cache);
  }
  const key = `${operation.operationId}:${status}:${mediaType}`;
  if (!cache.has(key)) {
    // report every problem with a response, not just the first one
    const ajv = getValidator(api).getAjv(ValidationContext.Response, { allErrors: true });
    cache.set(key, OpenAPIValidator.compileSchema(ajv, schema));
  }
  return cache.get(key) as ValidateFunction;
}

const validators = new WeakMap<object, OpenAPIValidator<any>>();

/**
 * The api's own validator, or a lazily compiling one if the api was created with validate: false
 */
function getValidator(api: OpenAPIBackend<any>): OpenAPIValidator<any> {
  if (api.validator) {
    return api.validator;
  }
  if (!validators.has(api)) {
    validators.set(
      api,
      new OpenAPIValidator({
        definition: api.definition,
        ajvOpts: api.ajvOpts,
        customizeAjv: api.customizeAjv,
        router: api.router,
        lazyCompileValidators: true,
        coerceTypes: api.coerceTypes,
      }),
    );
  }
  return validators.get(api) as OpenAPIValidator<any>;
}


/**
 * A response received by the test client
 */
export interface TestResponse<Body = any> {
  /** the HTTP status code */
  status: number;
  /** the response headers, with lowercase names */
  headers: { [name: string]: string };
  /** the response body. JSON is parsed. Other content is a string, or a Buffer for binary content */
  body: Body;
  /** the operationId of the operation the request was routed to */
  operationId: string | undefined;
  /** the matched operation */
  readonly operation: Operation | undefined;
  /**
   * the context openapi-backend built for the request. Undefined when the request didn't reach api.handleRequest()
   * in the same process as the test
   */
  readonly context: Context;
  /** the request that was sent */
  readonly request: SentRequest;
}

